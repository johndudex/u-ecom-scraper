EXTRACT_PRODUCT_JS = """
(src_url) => {
    const product = {
        title: '',
        price: '',
        availability: '',
        original_price: '',
        currency: '',
        url: window.location.href,
        src_url: src_url || '',
        location: '',
        remarks: ''
    };

    // JSON-LD
    const jsonldScripts = document.querySelectorAll('script[type="application/ld+json"]');
    let jsonld = null;
    for (const script of jsonldScripts) {
        try {
            const data = JSON.parse(script.textContent);
            // Content-type-agnostic: accept any typed JSON-LD entity with a name/title
            // (Product, Person, JobPosting, Article, etc.) — not just 'Product'.
            if (data['@type'] && (data.name || data.title)) { jsonld = data; break; }
            if (Array.isArray(data)) {
                for (const item of data) {
                    if (item['@type'] === 'Product') { jsonld = item; break; }
                }
            }
            if (jsonld) break;
        } catch(e) {}
    }

    // Title
    product.title = jsonld?.name ||
        document.querySelector('{TITLE_SELECTOR}')?.textContent?.trim() || '';

    // Price
    if (jsonld?.offers) {
        const offers = Array.isArray(jsonld.offers) ? jsonld.offers[0] : jsonld.offers;
        product.price = offers?.price || '';
        const highPrice = offers?.highPrice || '';
        if (highPrice && parseFloat(highPrice) > parseFloat(product.price || 0)) {
            product.original_price = highPrice;
        }
        product.currency = offers?.priceCurrency || 'USD';
        const avail = offers?.availability || '';
        product.availability = avail.includes('InStock') ? 'In Stock' : 'Out of Stock';
    } else {
        const priceEl = document.querySelector('{PRICE_SELECTOR}');
        product.price = priceEl?.textContent?.trim() || '';
        const origEl = document.querySelector('{ORIGINAL_PRICE_SELECTOR}');
        product.original_price = origEl?.textContent?.trim() || '';
        const stockEl = document.querySelector('{AVAILABILITY_SELECTOR}');
        if (stockEl) {
            const t = stockEl.textContent.toLowerCase();
            product.availability = t.includes('in stock') ? 'In Stock' : 'Out of Stock';
        }
    }

    return product;
}
"""

EXTRACT_PRODUCT_URLS_JS = """
() => {
    const links = document.querySelectorAll('{PRODUCT_LINK_SELECTOR}');
    const unique = new Set();
    links.forEach(a => {
        let href = a.getAttribute('href');
        if (href) {
            if (!href.startsWith('http')) {
                href = window.location.origin + href;
            }
            unique.add(href);
        }
    });
    return Array.from(unique);
}
"""


def scrape_product(page, url: str, src_url: str, index: int) -> dict:
    page.goto(url, wait_until="networkidle", timeout=PAGE_LOAD_TIMEOUT)
    page.wait_for_timeout(2000)

    data = page.evaluate(EXTRACT_PRODUCT_JS, src_url)

    return {
        "id": index,
        "title": data.get("title", ""),
        "price": data.get("price", ""),
        "availability": data.get("availability", ""),
        "original_price": data.get("original_price", ""),
        "currency": data.get("currency", ""),
        "url": url,
        "src_url": src_url,
        "location": data.get("location", ""),
        "status_code": 200,
        "scraped_at": datetime.now(timezone.utc).isoformat(),
        "remarks": data.get("remarks", ""),
    }


# SHARED DISCOVERY: pagination is imported from src/discovery.py, NOT defined
# inline. This prevents code_writer from rewriting/breaking the pagination loop
# (the root cause of the 20+ run whack-a-mole: code_writer treated the loop as
# editable prose and altered selectors, thresholds, and control flow every run).
# code_writer copies what it SEES — an import + call — so pagination stays
# deterministic. Only the extract_urls callback (EXTRACT_PRODUCT_URLS_JS) is
# site-specific and remains in this file for code_writer to adapt.
MAX_DISCOVER_PAGES = 200

# Last Phase-1 outcome, for the output's metadata.discovery_coverage block
# (discovery-coverage-gate contract §1). Module-level so BOTH discovery call
# sites in main() feed the same block without changing this function's
# list[str] contract. Skipped-state defaults are what a run that never
# discovered reports (url_list mode / checkpoint resume).
LAST_DISCOVERY: dict = {
    "ran_phase1": False,
    "skipped_reason": None,
    "stop_reason": "skipped",
    "discovered_urls": 0,
    "pages_visited": 0,
    "max_pages_hit": False,
}


def discover_product_urls(page) -> list[str]:
    def _extract(p):
        try:
            return p.evaluate(EXTRACT_PRODUCT_URLS_JS) or []
        except Exception:
            return []

    # Discovery config: read from sibling discovery_config.json (written by
    # scraper_analyzer → _invoke_code_writer) if present, else default to
    # load_more. This makes the pagination type DETERMINISTIC — driven by the
    # navigator's observation, not code_writer's guess. Falls back to
    # config_for_load_more when no config file exists (backward compat).
    import json as _dj
    _cfg = None
    _cfg_path = os.path.join(SCRIPT_DIR, "discovery_config.json")
    try:
        if os.path.isfile(_cfg_path):
            with open(_cfg_path) as _cf:
                _cfg = config_from_dict(_dj.load(_cf))
    except Exception:
        pass
    if _cfg is None:
        _cfg = config_for_load_more(max_pages=MAX_DISCOVER_PAGES)
    else:
        _cfg.max_pages = _cfg.max_pages or MAX_DISCOVER_PAGES

    result = discover_item_urls(page, PRODUCT_LISTING_URL, _extract, _cfg)
    logger.info(
        "discovery: stop_reason=%s pages=%d urls=%d param=%s strategies=%s",
        result.stop_reason, result.pages_visited, len(result.urls),
        result.param_used, _cfg.strategies,
    )
    LAST_DISCOVERY.update({
        "ran_phase1": True,
        "skipped_reason": None,
        "stop_reason": str(result.stop_reason),
        "discovered_urls": len(result.urls),
        "pages_visited": result.pages_visited,
        "max_pages_hit": result.max_pages_hit,
    })
    return result.urls


