# ── CLI CONTRACT — keep every line below when adapting ───────────────────────
# The pipeline launches this scraper with EXACTLY these names. A flag missing
# from the argparse below is STRIPPED at launch and discovery silently falls
# back to the seed file (input_urls.json). Same for the SCRAPER_LISTING_URL
# env read in main(). ADD flags if you need them; NEVER remove or rename:
#   --fresh-discovery  always (execution)     --listing-url  navigation/list_page
#   --query            search_term            --input/--sample/--limit  testing
#   --discover-only    Phase-1 probe          (+ SCRAPER_LISTING_URL env read)
# Source of truth: webapp/agents/constants.py
# ──────────────────────────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description=f"Playwright scraper for {SITE_NAME}")
    parser.add_argument("--sample", action="store_true", help="Scrape only 5 products")
    parser.add_argument("--limit", type=int, default=None, help="Max products to scrape")
    parser.add_argument("--input", type=str, default=None, help="Path to input URLs JSON file")
    parser.add_argument("--urls", nargs="+", default=None, help="Product URLs as arguments")
    parser.add_argument("--headless", action="store_true", help="Run in headless mode")
    parser.add_argument("--listing-url", type=str, default=None,
                        help="Listing page URL for Phase 1 discovery (pagination)")
    parser.add_argument("--fresh-discovery", action="store_true",
                        help="Force Phase 1 discovery even if input_urls.json exists")
    parser.add_argument("--discover-only", action="store_true",
                        help="Run Phase 1 discovery only (capped), skip Phase 2 extraction")
    args = parser.parse_args()

    start_time = time.time()

    logger.info("=" * 80)
    logger.info(f"Starting Playwright scraper for {SITE_NAME}")
    logger.info(f"Site: {SITE_URL}")
    logger.info(f"Output: {OUTPUT_FILE}")
    logger.info("=" * 80)

    product_urls = []

    # DETERMINISTIC DISCOVERY GATE (env-var driven, bypasses argparse/codegen):
    # run_execution sets SCRAPER_LISTING_URL=<url> for nav/list_page/search_term
    # jobs. When set, ALWAYS run Phase 1 discovery from that URL — regardless of
    # CLI flags (which code_writer may or may not declare) or input_urls.json
    # (which always exists with seed URLs and suppresses discovery in the old
    # `if not product_urls:` gate). This makes discovery DETERMINISTIC — not
    # dependent on code_writer faithfully copying --listing-url/--fresh-discovery
    # into argparse (it doesn't — verified across lw.com + uindex runs).
    _env_listing = os.environ.get("SCRAPER_LISTING_URL", "").strip()
    _env_force = os.environ.get("SCRAPER_FORCE_DISCOVERY", "").strip().lower() in ("1", "true", "yes")
    if _env_listing or _env_force or args.fresh_discovery or args.listing_url:
        global PRODUCT_LISTING_URL
        _listing = _env_listing or (args.listing_url if args.listing_url else "") or PRODUCT_LISTING_URL
        logger.info("Phase 1 discovery triggered (env/flag). Listing URL: %s", _listing)
        PRODUCT_LISTING_URL = _listing
        with sync_playwright() as p:
            browser = get_browser(p)
            context = browser.new_context(
                user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
                viewport={"width": 1920, "height": 1080},
            )
            page = context.new_page()
            product_urls = discover_product_urls(page)
            browser.close()
        if product_urls:
            save_urls_to_file(INPUT_FILE, product_urls)
    elif args.urls:
        product_urls = args.urls
        LAST_DISCOVERY["skipped_reason"] = "url_list_mode"
    elif args.input:
        product_urls = load_urls_from_file(args.input)
        LAST_DISCOVERY["skipped_reason"] = "url_list_mode"
    elif os.path.exists(INPUT_FILE):
        product_urls = load_urls_from_file(INPUT_FILE)
        # input_urls.json is this template's persisted discovery output; reusing
        # it means Phase 1 did not run this invocation.
        LAST_DISCOVERY["skipped_reason"] = "checkpoint_loaded"

    if not product_urls:
        logger.info("No input URLs found. Discovering products via browser...")
        with sync_playwright() as p:
            browser = get_browser(p)
            context = browser.new_context(
                user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
                viewport={"width": 1920, "height": 1080},
            )
            page = context.new_page()
            product_urls = discover_product_urls(page)
            browser.close()
        save_urls_to_file(INPUT_FILE, product_urls)

    # --discover-only: run a CAPPED Phase 1 discovery (5 pages max) for testing,
    # then exit without Phase 2. This lets _probe_phase1_discovery verify that
    # discovery actually works (finds >0 URLs, paginates past page 1) without
    # needing the full ~800s for 200 pages. The probe has a 180s budget — plenty
    # for 5 pages × ~4s = ~20s.
    # NOTE: opens its OWN browser page — the discovery gate above may have
    # already closed its browser (browser.close() at the end of the gate's
    # with-block), and a `page` handle from a closed browser makes every
    # navigation fail silently ("target closed" is swallowed by
    # _discovery_goto) → always found=0 / stop_reason=navigate_error with
    # exit 0 (the pre-fix bug: two rmwilliams probe artifacts proved it).
    if args.discover_only:
        _dcfg = None
        try:
            import json as _dj2
            _dcfg_path2 = os.path.join(SCRIPT_DIR, "discovery_config.json")
            if os.path.isfile(_dcfg_path2):
                with open(_dcfg_path2) as _cf2:
                    _dcfg = config_from_dict(_dj2.load(_cf2))
        except Exception:
            pass
        if _dcfg is None:
            _dcfg = config_for_load_more(max_pages=5)
        else:
            _dcfg.max_pages = 5  # cap for testing

        def _extract_probe(p):
            try:
                return p.evaluate(EXTRACT_PRODUCT_URLS_JS) or []
            except Exception:
                return []

        with sync_playwright() as p:
            browser = get_browser(p)
            context = browser.new_context(
                user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
                viewport={"width": 1920, "height": 1080},
            )
            probe_page = context.new_page()
            _probe_result = discover_item_urls(probe_page, PRODUCT_LISTING_URL, _extract_probe, _dcfg)
            browser.close()
        logger.info(
            "discover-only: stop_reason=%s pages=%d urls=%d",
            _probe_result.stop_reason, _probe_result.pages_visited, len(_probe_result.urls),
        )
        # discovery_coverage — contract §1, same 9 keys the full run emits below
        # (plus the pages_visited diagnostic), so a probe output and an
        # execution output are read by the same code path.
        _probe_coverage = {
            "ran_phase1": True,
            "skipped_reason": None,
            "stop_reason": str(_probe_result.stop_reason),
            "found": 0,  # Phase 2 skipped by design
            "discovered_urls": len(_probe_result.urls),
            "expected_total": None,
            "dimensions_iterated": 0,
            "dimensions_total": 0,
            "max_pages_hit": _probe_result.max_pages_hit,
            "pages_visited": _probe_result.pages_visited,
        }
        output = {
            "site": {
                "name": SITE_NAME,
                "url": SITE_URL,
                "platform": PLATFORM,
                "scraping_method": SCRAPING_METHOD,
                "scraped_at": datetime.now(timezone.utc).isoformat(),
            },
            "products": [],
            "metadata": {
                "total_discovered": len(_probe_result.urls),
                "discovery_coverage": _probe_coverage,
            },
        }
        with open(OUTPUT_FILE, "w") as _of:
            json.dump(output, _of, indent=2)
        logger.info("discover-only: wrote %d discovered URLs to %s", len(_probe_result.urls), OUTPUT_FILE)
        return

    if args.sample:
        product_urls = product_urls[:20]
    if args.limit:
        product_urls = product_urls[: args.limit]

    logger.info(f"Total products to scrape: {len(product_urls)}")

    results = []
    failed = 0

    proxy_server = build_proxy_url("datacenter", proxy_config, country=detect_country(SITE_URL)) or None
    launch_args = {
        "headless": args.headless,
        "args": [
            "--disable-blink-features=AutomationControlled",
            "--disable-infobars",
            "--no-first-run",
        ],
    }
    if proxy_server:
        launch_args["proxy"] = {"server": proxy_server}

    with sync_playwright() as p:
        browser = get_browser(p, headless=args.headless, proxy=proxy_server)
        context = browser.new_context(
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
            viewport={"width": 1920, "height": 1080},
        )
        page = context.new_page()

        logger.info("Warming up session...")
        page.goto(SITE_URL, wait_until="networkidle", timeout=PAGE_LOAD_TIMEOUT)
        page.wait_for_timeout(5000)

        for i, url in enumerate(product_urls):
            try:
                product = scrape_product(page, url, SRC_URL, i + 1)
                # Content-type-agnostic validity: accept if ANY substantive field
                # (not just 'title') is present — rescues Person/job/article items.
                _BK = {"url", "src_url", "scraped_at", "status_code", "remarks", "id", "title"}
                if any(v for k, v in product.items() if k not in _BK):
                    results.append(product)
                else:
                    logger.warning(f"No substantive data extracted from: {url}")
                    failed += 1
            except Exception as e:
                logger.error(f"Error processing {url}: {e}")
                failed += 1

            if (i + 1) % 25 == 0:
                percent = ((i + 1) / len(product_urls)) * 100
                logger.info(f"Progress: [{i + 1}/{len(product_urls)}] ({percent:.1f}%)")

            time.sleep(DELAY_BETWEEN_REQUESTS)

        browser.close()

    # discovery_coverage — discovery-coverage-gate contract §1. Always emitted
    # (even when Phase 1 was skipped) so the gate reads a uniform schema.
    if LAST_DISCOVERY.get("ran_phase1"):
        _stop_reason = LAST_DISCOVERY.get("stop_reason", "no_next_link")
    else:
        _stop_reason = "skipped"
    discovery_coverage = {
        "ran_phase1": LAST_DISCOVERY.get("ran_phase1", False),
        "skipped_reason": LAST_DISCOVERY.get("skipped_reason"),
        "stop_reason": _stop_reason,
        "found": len(results),
        "discovered_urls": LAST_DISCOVERY.get("discovered_urls", 0),
        "expected_total": None,
        "dimensions_iterated": 0,
        "dimensions_total": 0,
        "max_pages_hit": LAST_DISCOVERY.get("max_pages_hit", False),
        # Extra diagnostic (not part of §1; no consumer reads it today).
        "pages_visited": LAST_DISCOVERY.get("pages_visited", 0),
    }

    output = {
        "site": {
            "name": SITE_NAME,
            "url": SITE_URL,
            "platform": PLATFORM,
            "scraping_method": SCRAPING_METHOD,
            "scraped_at": datetime.now(timezone.utc).isoformat(),
        },
        "products": results,
        "metadata": {
            "scraping_duration_seconds": round(time.time() - start_time, 2),
            "failed_products": failed,
            "rate_limit_delay": DELAY_BETWEEN_REQUESTS,
            "discovered_urls": LAST_DISCOVERY.get("discovered_urls", 0),
            "discovery_coverage": discovery_coverage,
        },
    }

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    logger.info("=" * 80)
    logger.info("EXTRACTION COMPLETE")
    logger.info(f"Total: {len(results)}, Failed: {failed}")
    logger.info(f"Duration: {round(time.time() - start_time, 2)}s")
    logger.info(f"Output: {OUTPUT_FILE}")
    logger.info("=" * 80)


if __name__ == "__main__":
    main()
