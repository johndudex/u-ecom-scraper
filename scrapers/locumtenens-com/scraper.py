# PHASE 1: URL DISCOVERY (Form-Search)
# ═══════════════════════════════════════════════════════════════════════════════

def _discover_urls_via_form_search(
    state: dict,
    max_pages: Optional[int] = None,
    limit: Optional[int] = None,
) -> list[str]:
    """Phase 1: Discover job URLs by iterating through form sort options.

    The search form at FORM_BASE_URL has a <select name="sort"> that must
    be set (returns 500 without one). We iterate ALL sort options, POST
    once per option, extract job links, and paginate through results.
    """
    all_urls: list[str] = []
    form_html = ""

    # Step 1: GET the form page to find sort options + hidden fields
    logger.info("Phase 1: Loading form page -> %s", FORM_BASE_URL)
    try:
        form_html, final_url, status = _http_get(FORM_BASE_URL)
    except Exception as exc:
        logger.error("Phase 1: Failed to load form page: %s", exc)
        _set_stop_reason(state, "navigate_error")
        return []

    if status >= 400:
        logger.error("Phase 1: Form page returned HTTP %d", status)
        _set_stop_reason(state, "navigate_error")
        return []

    # Extract links from initial GET response (page 1 results are already here)
    initial_links = _extract_job_links(form_html, final_url)
    if initial_links:
        all_urls.extend(initial_links)
        logger.info("Phase 1: Extracted %d links from initial GET", len(initial_links))

    # Step 2: Parse sort options
    sort_options = _extract_select_options(form_html, FORM_SELECT_NAME)
    if not sort_options:
        logger.warning("Phase 1: No sort options found; trying direct page extraction")
        # Try extracting links from the GET response directly
        page_links = _extract_job_links(form_html, final_url)
        all_urls.extend(page_links)
        if not all_urls:
            sort_options = ["0", "1", "2"]  # fallback
        else:
            logger.info("Phase 1: Extracted %d links from initial GET", len(all_urls))

    state["dimensions_total"] = len(sort_options)
    logger.info("Phase 1: Found %d sort options: %s", len(sort_options), sort_options)

    # Step 3: For each sort option, POST and extract links + paginate
    for opt_idx, opt_value in enumerate(sort_options):
        if limit and len(all_urls) >= limit:
            logger.info("Phase 1: Reached limit=%d", limit)
            _set_stop_reason(state, "max_pages_hit")
            break

        state["dimensions_iterated"] = opt_idx + 1
        logger.info("Phase 1 [%d/%d]: Submitting sort='%s'", opt_idx + 1, len(sort_options), opt_value)

        # Extract hidden fields (ASP.NET may need ViewState etc.)
        hidden_fields = _extract_hidden_fields(form_html)

        # Build POST data
        post_data = dict(hidden_fields)
        post_data[FORM_SELECT_NAME] = opt_value

        try:
            page_html, page_url, page_status = _http_post(FORM_ACTION, post_data)
        except Exception as exc:
            logger.warning("Phase 1: sort='%s' POST failed: %s", opt_value, exc)
            continue

        if page_status >= 400:
            logger.warning("Phase 1: sort='%s' returned HTTP %d", opt_value, page_status)
            continue

        # Extract job links from this page
        page_links = _extract_job_links(page_html, page_url)
        new_links = [u for u in page_links if u not in set(all_urls)]
        all_urls.extend(new_links)
        logger.info("Phase 1: sort='%s' -> %d links (%d new, %d total)",
                     opt_value, len(page_links), len(new_links), len(all_urls))

        # Paginate within this sort option
        current_page = 1
        while True:
            if max_pages and current_page >= max_pages:
                state["max_pages_hit"] = True
                _set_stop_reason(state, "max_pages_hit")
                break
            if limit and len(all_urls) >= limit:
                _set_stop_reason(state, "max_pages_hit")
                break

            next_url = _get_next_page_url(page_url, current_page + 1, page_html)
            if not next_url:
                break

            logger.debug("Phase 1: Paginating to page %d (sort='%s')", current_page + 1, opt_value)
            try:
                p_html, p_url, p_status = _http_get(next_url)
            except Exception as exc:
                logger.warning("Phase 1: pagination failed at page %d: %s", current_page + 1, exc)
                _set_stop_reason(state, "navigate_error")
                break

            if p_status >= 400:
                logger.warning("Phase 1: page %d returned HTTP %d", current_page + 1, p_status)
                break

            p_links = _extract_job_links(p_html, p_url)
            p_new = [u for u in p_links if u not in set(all_urls)]

            if not p_new:
                logger.info("Phase 1: No new items on page %d (sort='%s'), stopping",
                            current_page + 1, opt_value)
                _set_stop_reason(state, "no_new_items")
                break

            all_urls.extend(p_new)
            current_page += 1
            page_html = p_html
            page_url = p_url
            time.sleep(DELAY_BETWEEN_REQUESTS)

        _write_checkpoint(all_urls)
        time.sleep(DELAY_BETWEEN_REQUESTS)

    unique = list(dict.fromkeys(all_urls))
    if limit:
        unique = unique[:limit]

    logger.info("Phase 1: Discovered %d unique job URLs", len(unique))
    return unique


def _get_next_page_url(current_url: str, next_page_num: int, html: str) -> Optional[str]:
    """Determine the URL for the next page of results.

    Tries semantic next-button links in HTML first; falls back to
    constructing ?page=N via PAGE_PARAM_NAME.
    """
    # 1. Try semantic next-button links in HTML
    next_patterns = [
        r'<a[^>]*rel=["\']next["\'][^>]*href=["\']([^"\']*)["\']',
        r'<a[^>]*href=["\']([^"\']*)["\'][^>]*rel=["\']next["\']',
        r'<a[^>]*class=["\'][^"\']*next[^"\']*["\'][^>]*href=["\']([^"\']*)["\']',
        r'<a[^>]*href=["\']([^"\']*)["\'][^>]*class=["\'][^"\']*next[^"\']*["\']',
        r'<li[^>]*class=["\'][^"\']*next[^"\']*["\'][^>]*>\s*<a[^>]*href=["\']([^"\']*)["\']',
    ]
    for pattern in next_patterns:
        match = re.search(pattern, html, re.IGNORECASE)
        if match:
            href = match.group(1)
            if href:
                full = urljoin(current_url, href)
                return full

    # 2. Fall back to URL parameter construction
    if PAGE_PARAM_NAME:
        return _set_query_param(current_url, PAGE_PARAM_NAME, next_page_num)

    return None


