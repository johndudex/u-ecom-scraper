def _extract_json_ld(html: str) -> list[dict]:
    """Extract all JSON-LD <script> blocks from HTML (handles arrays + @graph)."""
    blocks = []
    pattern = r'<script[^>]*type=["\']application/ld\+json["\'][^>]*>(.*?)</script>'
    for match in re.finditer(pattern, html, re.DOTALL):
        raw = match.group(1).strip()
        try:
            data = json.loads(raw)
            if isinstance(data, list):
                blocks.extend(data)
            elif isinstance(data, dict):
                # Unwrap @graph if present
                if "@graph" in data and isinstance(data["@graph"], list):
                    blocks.extend(data["@graph"])
                else:
                    blocks.append(data)
        except (json.JSONDecodeError, ValueError):
            pass
    return blocks


def _extract_job_links(html: str, base_url: str) -> list[str]:
    """Extract job posting URLs from listing/search results page HTML."""
    links = []
    for match in JOB_URL_PATTERN.finditer(html):
        href = match.group(1)
        full_url = urljoin(base_url, href)
        # Clean URL (remove query params and fragments for dedup)
        parsed = urlparse(full_url)
        clean_url = f"{parsed.scheme}://{parsed.netloc}{parsed.path}"
        links.append(clean_url)
    return list(dict.fromkeys(links))


def _extract_select_options(html: str, select_name: str) -> list[str]:
    """Extract all option values from a <select> by name attribute."""
    pattern = rf'<select[^>]*name=["\']?{re.escape(select_name)}["\']?[^>]*>(.*?)</select>'
    match = re.search(pattern, html, re.DOTALL | re.IGNORECASE)
    if not match:
        return []
    inner = match.group(1)
    options = re.findall(r'<option[^>]*value=["\']([^"\']*)["\']', inner, re.IGNORECASE)
    return options


def _extract_hidden_fields(html: str) -> dict:
    """Extract all hidden input fields from HTML (for ASP.NET forms)."""
    fields = {}
    pattern = r'<input[^>]*type=["\']hidden["\'][^>]*>'
    for match in re.finditer(pattern, html, re.IGNORECASE):
        tag = match.group(0)
        name_match = re.search(r'name=["\']([^"\']*)["\']', tag, re.IGNORECASE)
        value_match = re.search(r'value=["\']([^"\']*)["\']', tag, re.IGNORECASE)
        if name_match:
            name = name_match.group(1)
            value = value_match.group(1) if value_match else ""
            fields[name] = value
    return fields


def _set_query_param(url: str, param: str, value) -> str:
    """Return url with the query param REPLACED (not appended)."""
    p = urlparse(url)
    qs = [(k, v) for k, v in parse_qsl(p.query, keep_blank_values=True) if k != param]
    qs.append((param, str(value)))
    return urlunparse(p._replace(query=urlencode(qs)))


def _strip_tags(text: str) -> str:
    """Remove HTML tags and unescape entities."""
    text = re.sub(r'<[^>]+>', '', text)
    return unescape(text).strip()


def _is_soft_404(html: str, status_code: int, final_url: str, requested_url: str) -> Optional[str]:
    """Detect soft 404 / not-found pages. Returns reason string or None."""
    if status_code >= 400:
        return f"HTTP {status_code}"

    # Check page title
    title_match = re.search(r'<title[^>]*>(.*?)</title>', html, re.DOTALL | re.IGNORECASE)
    if title_match:
        title = _strip_tags(title_match.group(1)).lower()
        for kw in ["not found", "error page", "page not found"]:
            if kw in title:
                return f"Soft 404: title contains '{kw}'"

    # Check H1
    h1_match = re.search(r'<h1[^>]*>(.*?)</h1>', html, re.DOTALL | re.IGNORECASE)
    if h1_match:
        h1 = _strip_tags(h1_match.group(1)).lower()
        for kw in ["not found", "no longer available", "expired", "removed"]:
            if kw in h1:
                return f"Soft 404: h1 contains '{kw}'"

    return None


