def _parse_json_ld(html: str) -> list[dict]:
    """Parse all JSON-LD <script> blocks from HTML."""
    blocks = []
    for match in re.finditer(
        r'<script[^>]*type=["\']application/ld\+json["\'][^>]*>(.*?)</script>',
        html, re.I | re.S,
    ):
        raw = match.group(1).strip()
        if not raw:
            continue
        try:
            data = json.loads(raw)
        except (json.JSONDecodeError, ValueError):
            continue
        # Handle @graph arrays
        if isinstance(data, dict):
            if "@graph" in data:
                blocks.extend([g for g in data["@graph"] if isinstance(g, dict)])
            else:
                blocks.append(data)
        elif isinstance(data, list):
            blocks.extend([d for d in data if isinstance(d, dict)])
    return blocks


def _strip_html(text: str) -> str:
    """Strip HTML tags and decode entities."""
    if not text:
        return ""
    # Remove script/style
    text = re.sub(r'<(script|style)[^>]*>.*?</\1>', '', text, flags=re.I | re.S)
    # Remove tags
    text = re.sub(r'<[^>]+>', ' ', text)
    # Decode entities
    text = unescape(text)
    # Collapse whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    return text


def _extract_label_value(html: str, label: str) -> str:
    """Find a 'Label: value' pattern in the job details section (DOM text search).

    Handles patterns like:
      - <strong>Specialty:</strong> Allergy
      - <dt>Specialty</dt><dd>Allergy</dd>
      - <th>Specialty</th><td>Allergy</td>
      - <span>Specialty:</span> Allergy
      - Plain text "Specialty: Allergy"
    """
    patterns = [
        r'<(?:strong|b|label)[^>]*>\s*' + re.escape(label) + r'\s*:?\s*</(?:strong|b|label)>\s*([^<]+)',
        r'<dt[^>]*>\s*' + re.escape(label) + r'\s*:?\s*</dt>\s*<dd[^>]*>(.*?)</dd>',
        r'<th[^>]*>\s*' + re.escape(label) + r'\s*:?\s*</th>\s*<td[^>]*>(.*?)</td>',
        r'<span[^>]*>\s*' + re.escape(label) + r'\s*:?\s*</span>\s*([^<]+)',
        re.escape(label) + r'\s*:\s*([^\n<]+)',
    ]
    for pat in patterns:
        m = re.search(pat, html, re.I | re.S)
        if m:
            val = _strip_html(m.group(1)).strip()
            val = val.rstrip(":").strip()
            if val:
                return val
    return ""


def _detect_soft_404(html: str, json_ld_blocks: list[dict], item: dict) -> bool:
    """Detect soft-404 pages. Returns True and updates item['remarks'] if detected."""
    title_text = ""
    h1_match = re.search(r'<h1[^>]*>(.*?)</h1>', html, re.I | re.S)
    if h1_match:
        title_text = _strip_html(h1_match.group(1)).lower()

    page_title = ""
    title_tag_match = re.search(r'<title[^>]*>(.*?)</title>', html, re.I | re.S)
    if title_tag_match:
        page_title = _strip_html(title_tag_match.group(1)).lower()

    soft_404_markers = [
        "not found", "no longer available", "unavailable", "discontinued",
        "job closed", "job removed", "no longer active", "expired",
        "this job has been filled", "position filled",
    ]
    combined = title_text + " " + page_title
    for marker in soft_404_markers:
        if marker in combined:
            item["remarks"] = f"Soft 404: {marker}"
            return True

    # Check for JobPosting in JSON-LD
    has_job_posting = any(
        block.get("@type") == "JobPosting"
        for block in json_ld_blocks
    )
    if not has_job_posting:
        if not title_text or "job" not in title_text:
            item["remarks"] = "Soft 404: no JobPosting structured data found"
            return True

    return False


def _extract_item_data(url: str, src_url: str) -> dict:
    """Phase 2: Extract structured data from a single job page via HTTP.

    Code Writer adapted: Extracts JSON-LD JobPosting fields + DOM text labels
    for specialty, board certification, compensation, government, etc.
    """
    item: dict = {
        "url": url,
        "src_url": src_url,
        "status_code": 0,
        "scraped_at": datetime.now(timezone.utc).isoformat(),
        "remarks": "",
    }

    sess = _get_session()
    try:
        resp = sess.get(url, timeout=REQUEST_TIMEOUT, allow_redirects=True)
    except Exception as exc:
        logger.error("Phase 2: Failed to load %s: %s", url[:80], exc)
        item["remarks"] = f"Error: {str(exc)[:200]}"
        return item

    item["status_code"] = resp.status_code
    if resp.status_code != 200:
        item["remarks"] = f"HTTP {resp.status_code}"
        return item

    html = resp.text

    # Check for redirect to a different URL (soft-404 indicator)
    final_url = resp.url
    if final_url != url and not _is_job_url(final_url):
        item["remarks"] = "Soft 404: redirected to non-job URL"
        return item

    # Parse JSON-LD
    json_ld_blocks = _parse_json_ld(html)

    # Soft 404 detection
    if _detect_soft_404(html, json_ld_blocks, item):
        return item

    # ── Extract from JSON-LD JobPosting ──────────────────────────────
    job_posting = None
    for block in json_ld_blocks:
        if block.get("@type") == "JobPosting":
            job_posting = block
            break

    if job_posting:
        item["title"] = job_posting.get("title", "") or ""
        item["description"] = _strip_html(job_posting.get("description", "") or "")
        item["date_posted"] = job_posting.get("datePosted", "") or ""
        item["employment_type"] = job_posting.get("employmentType", "") or ""

        # Hiring organization
        org = job_posting.get("hiringOrganization", {})
        if isinstance(org, dict):
            item["hiring_organization"] = org.get("name", "") or ""
            item["company"] = org.get("name", "") or ""

        # Industry
        item["industry"] = job_posting.get("industry", "") or ""

        # Job location
        loc = job_posting.get("jobLocation", {})
        if isinstance(loc, dict):
            addr = loc.get("address", {})
            if isinstance(addr, dict):
                item["location"] = addr.get("addressLocality", "") or ""
                item["address_country"] = addr.get("addressCountry", "") or ""
                item["address_region"] = addr.get("addressRegion", "") or ""

        # Valid through
        item["valid_through"] = job_posting.get("validThrough", "") or ""

    # ── DOM text fallbacks ────────────────────────────────────────────
    # h1 title (fallback if JSON-LD missing)
    h1_match = re.search(r'<h1[^>]*>(.*?)</h1>', html, re.I | re.S)
    h1_text = ""
    if h1_match:
        h1_text = _strip_html(h1_match.group(1))

    if not item.get("title"):
        item["title"] = h1_text
    item["h1_title"] = h1_text

    # Job details section labels (DOM text search)
    # Code Writer adapted: Extract labeled fields from job details section
    item["specialty"] = _extract_label_value(html, "Specialty")
    item["board_certification"] = _extract_label_value(html, "Board Certification")
    item["compensation_info"] = _extract_label_value(html, "Compensation")
    item["government"] = _extract_label_value(html, "Government")
    item["on_call"] = _extract_label_value(html, "On Call")
    item["telemedicine"] = _extract_label_value(html, "Telemedicine")
    item["job_type"] = _extract_label_value(html, "Job Type")

    # Location fallback from label
    if not item.get("location"):
        item["location"] = _extract_label_value(html, "Location")

    return item


def _error_item(url: str, src_url: str, error: str) -> dict:
    return {
        "url": url,
        "src_url": src_url,
        "status_code": 0,
        "scraped_at": datetime.now(timezone.utc).isoformat(),
        "remarks": f"Error: {error[:200]}",
    }


# ═══════════════════════════════════════════════════════════════════════════════
# PHASE 2: CONCURRENT EXTRACTION
# ═══════════════════════════════════════════════════════════════════════════════


def _extract_all(urls: list[str], src_url: str) -> list[dict]:
    """Extract data from all URLs concurrently, preserving order."""
    results: dict[int, dict] = {}
    total = len(urls)

    def _worker(idx: int, url: str) -> tuple[int, dict]:
        try:
            return idx, _extract_item_data(url, src_url)
        except Exception as exc:
            logger.error("Phase 2: exception for %s: %s", url[:80], exc)
            return idx, _error_item(url, src_url, str(exc))

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as pool:
        futures = {
            pool.submit(_worker, i, url): i
            for i, url in enumerate(urls)
        }
        done = 0
        for future in as_completed(futures):
            idx, item = future.result()
            results[idx] = item
            done += 1
            if done % 10 == 0 or done == total:
                logger.info("Phase 2: %d/%d items extracted (%.1f%%)",
                            done, total, done / total * 100)

    return [results[i] for i in range(total)]


