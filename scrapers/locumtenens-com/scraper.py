_thread_local = threading.local()


def _get_session() -> requests.Session:
    """Thread-local requests.Session — each worker gets its own."""
    if not hasattr(_thread_local, "session"):
        s = requests.Session()
        s.headers.update(HEADERS)
        _thread_local.session = s
    return _thread_local.session


def _http_get(url: str):
    """GET url → (html, final_url, status_code). final_url captured from resp.url."""
    session = _get_session()
    resp = session.get(url, timeout=30, allow_redirects=True)
    return resp.text, str(resp.url), resp.status_code


def _http_post(url: str, data: dict):
    """POST url with data → (html, final_url, status_code)."""
    session = _get_session()
    resp = session.post(url, data=data, timeout=30, allow_redirects=True)
    return resp.text, str(resp.url), resp.status_code

