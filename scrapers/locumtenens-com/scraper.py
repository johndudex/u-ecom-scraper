def _normalize_url(href: str, base: str = SITE_URL) -> str:
    """Convert a relative or protocol-relative href to an absolute URL."""
    if not href:
        return ""
    href = href.strip()
    if href.startswith("//"):
        return "https:" + href
    if href.startswith("/"):
        return base.rstrip("/") + href
    if not href.startswith("http"):
        return urljoin(base, href)
    return href


def _extract_job_links(html: str) -> list[str]:
    """Extract job-detail page URLs from an HTML listing page.

    Matches hrefs containing ``/job-NNNNN`` patterns and normalizes them.
    """
    hrefs = re.findall(r'href=["\']([^"\']+)["\']', html, re.I)
    job_urls = []
    seen = set()
    for href in hrefs:
        if ITEM_LINK_PATTERN.search(href):
            full_url = _normalize_url(href)
            if full_url not in seen:
                seen.add(full_url)
                job_urls.append(full_url)
    return job_urls


def _build_page_url(url: str, page_num: int) -> str:
    """Return ``url`` with the ``page`` query param set to ``page_num``."""
    p = urlparse(url)
    qs = [(k, v) for k, v in parse_qsl(p.query, keep_blank_values=True) if k != PAGE_PARAM_NAME]
    qs.append((PAGE_PARAM_NAME, str(page_num)))
    return urlunparse(p._replace(query=urlencode(qs)))


def _is_job_url(href: str) -> bool:
    """Check if a URL looks like a job detail page."""
    return bool(ITEM_LINK_PATTERN.search(href))


