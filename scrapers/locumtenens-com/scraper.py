def main():
    parser = argparse.ArgumentParser(description=f"{SITE_NAME} Job Posting Scraper")
    parser.add_argument("--input", type=str, help="Path to input URLs JSON file")
    parser.add_argument("--urls", nargs="+", help="Job URLs as CLI arguments")
    parser.add_argument("--query", type=str, default=None,
                        help="Search query (kept for compat; uses form-search by default)")
    parser.add_argument("--sample", action="store_true",
                        help="Scrape first 5 items (from input_urls.json)")
    parser.add_argument("--limit", type=int, default=None, help="Max items to scrape")
    parser.add_argument("--no-proxy", action="store_true",
                        help="Disable proxy (no proxy used by default for this site)")
    parser.add_argument("--discover-only", action="store_true",
                        help="Run Phase 1 only; skip Phase 2")
    parser.add_argument("--fresh-discovery", action="store_true",
                        help="Ignore checkpoint; run Phase 1 from scratch")
    args = parser.parse_args()

    limit = 5 if args.sample else args.limit

    start_time = time.time()
    discovered_urls: list[str] = []
    items: list[dict] = []
    src_url_base = FORM_ACTION

    discovery_state = _new_discovery_state()
    ran_phase1 = False
    skipped_reason: Optional[str] = None

    # ── Determine input URLs ──
    # Code Writer adapted: --query forces Phase 1 discovery even when --sample
    # is also set. Priority: --input > --urls > Phase1 (--query/default) > --sample
    if args.input:
        # --input takes precedence over checkpoint — skip checkpoint load entirely
        logger.info("Loading URLs from --input: %s", args.input)
        try:
            with open(args.input, "r") as f:
                data = json.load(f)
            if isinstance(data, dict):
                discovered_urls = data.get("urls", [])
            elif isinstance(data, list):
                discovered_urls = data
            else:
                discovered_urls = []
            logger.info("Loaded %d URLs from input file", len(discovered_urls))
            skipped_reason = "input_file"
        except Exception as exc:
            logger.error("Failed to load input file: %s", exc)
    elif args.urls:
        discovered_urls = args.urls
        skipped_reason = "cli_urls"
        logger.info("Using %d URLs from --urls", len(discovered_urls))
    elif args.sample and not args.query:
        # --sample WITHOUT --query: quick test from input_urls.json
        input_path = os.path.join(SCRIPT_DIR, "input_urls.json")
        try:
            with open(input_path, "r") as f:
                data = json.load(f)
            discovered_urls = data.get("urls", []) if isinstance(data, dict) else data
            if limit:
                discovered_urls = discovered_urls[:limit]
            skipped_reason = "sample"
            logger.info("Sample mode: loaded %d URLs from input_urls.json", len(discovered_urls))
        except Exception as exc:
            logger.error("Sample mode: failed to load input_urls.json: %s", exc)
            sys.exit(1)
    else:
        # Default mode (no-args) or --query: Phase 1 form-search discovery.
        # Check checkpoint first (unless --fresh-discovery), then run discovery.
        if not args.fresh_discovery:
            checkpoint_urls = _load_checkpoint()
            if checkpoint_urls:
                discovered_urls = checkpoint_urls
                skipped_reason = "checkpoint_loaded"
                logger.info("Phase 1: SKIPPED (resumed from checkpoint with %d URLs)", len(discovered_urls))

        if not discovered_urls:
            ran_phase1 = True
            logger.info("Phase 1: Starting form-search discovery")
            discovered_urls = _discover_urls_via_form_search(discovery_state, MAX_PAGES, limit)
            _write_checkpoint(discovered_urls)

    if not ran_phase1 and not skipped_reason:
        _set_stop_reason(discovery_state, "skipped")
    elif not ran_phase1:
        _set_stop_reason(discovery_state, "skipped")

    # ── Phase 2: Extract data ──────────────────────────────────────────
    if args.discover_only:
        logger.info("--discover-only: skipping Phase 2 extraction")
    elif discovered_urls:
        total = len(discovered_urls)
        logger.info("Phase 2: Extracting data from %d items", total)

        # Concurrent extraction with ThreadPoolExecutor (HTTP-based Phase 2)
        with ThreadPoolExecutor(max_workers=8) as executor:
            future_to_idx = {}
            for idx, url in enumerate(discovered_urls):
                future = executor.submit(_extract_item, url, src_url_base)
                future_to_idx[future] = idx

            results: list[Optional[dict]] = [None] * total
            for future in as_completed(future_to_idx):
                idx = future_to_idx[future]
                try:
                    results[idx] = future.result()
                except Exception as exc:
                    logger.error("Failed to extract %s: %s", discovered_urls[idx][:80], exc)
                    results[idx] = _error_item(discovered_urls[idx], src_url_base, str(exc))

                done = sum(1 for r in results if r is not None)
                logger.info("Progress: [%d/%d] (%.1f%%)", done, total, (done / total) * 100)

            items = [r for r in results if r is not None]
    else:
        logger.warning("No URLs to process")

    # ── Output filter: drop items without title + at least one core field ─
    _extra = [f for f in CORE_FILTER_FIELDS if f and f != "title"]
    _before = len(items)
    items = [it for it in items
             if it.get("title") and (not _extra or any(it.get(f) for f in _extra))]
    if len(items) != _before:
        logger.info("Output filter: %d -> %d items (dropped %d without core fields)",
                     _before, len(items), _before - len(items))

    # ── Discovery coverage block ───────────────────────────────────────
    discovery_coverage = {
        "stop_reason": discovery_state["stop_reason"],
        "found": len(items),
        "discovered_urls": len(discovered_urls),
        "expected_total": COVERAGE_TARGET_TOTAL,
        "dimensions_iterated": discovery_state["dimensions_iterated"],
        "dimensions_total": discovery_state["dimensions_total"],
        "max_pages_hit": discovery_state["max_pages_hit"],
        "ran_phase1": ran_phase1,
        "skipped_reason": skipped_reason,
    }

    output = {
        "site": {
            "name": SITE_NAME,
            "url": SITE_URL,
            "platform": PLATFORM,
            "scraping_method": "http_requests",
            "scraped_at": datetime.now(timezone.utc).isoformat(),
        },
        OUTPUT_KEY: items,
        "metadata": {
            "scraping_duration_seconds": round(time.time() - start_time, 1),
            "discovered_urls": len(discovered_urls),
            "extracted_items": len(items),
            "discovery_coverage": discovery_coverage,
        },
    }

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d_%H%M%S")
    output_filename = os.path.join(SCRIPT_DIR, f"output_{timestamp}.json")

    with open(output_filename, "w", encoding="utf-8") as f:
        # _OUTPUT_FILTER_APPLIED — drop non-item pages (content-type aware)
        _FILTER_FIELDS = ['company', 'location', 'description']
        try:
            _before = len(output.get(OUTPUT_KEY, []))
            output[OUTPUT_KEY] = [p for p in output.get(OUTPUT_KEY, []) if p.get('title') and (p.get('company') or p.get('location') or p.get('description'))]
            _after = len(output[OUTPUT_KEY])
            if _before != _after:
                logger.info('output filter: %d → %d items (removed %d without title+company,location,description)',
                             _before, _after, _before - _after)
        except Exception:
            pass


        json.dump(output, f, indent=2, ensure_ascii=False, default=str)

    logger.info(
        "Done: %d/%d items in %.1fs (stop_reason=%s) -> %s",
        len([i for i in items if i.get("title")]),
        len(discovered_urls),
        time.time() - start_time,
        discovery_state["stop_reason"],
        output_filename,
    )


if __name__ == "__main__":
    main()
