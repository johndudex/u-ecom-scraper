def _get_specialty_options() -> list[tuple[str, str]]:
    """Fetch the QuickSearch form page and extract all <select> options.

    Returns a list of (value, label) tuples for the Specialties select.
    """
    sess = _get_session()
    specialties: list[tuple[str, str]] = []

    # Try fetching the form page that contains the Specialties select
    for form_page_url in [FORM_BASE_URL, SEARCH_URL, SITE_URL]:
        try:
            resp = sess.get(form_page_url, timeout=REQUEST_TIMEOUT, allow_redirects=True)
            if resp.status_code != 200:
                continue
            html = resp.text
            # Look for the <select name="Specialties">
            select_match = re.search(
                r'<select[^>]*name=["\']' + re.escape(FORM_SELECT_NAME) + r'["\'][^>]*>(.*?)</select>',
                html, re.I | re.S,
            )
            if select_match:
                inner = select_match.group(1)
                options = re.findall(
                    r'<option[^>]*value=["\']([^"\']+)["\'][^>]*>([^<]+)</option>',
                    inner, re.I,
                )
                specialties = [(v.strip(), t.strip()) for v, t in options if v.strip()]
                if specialties:
                    logger.info("Phase 1: found %d specialty options in <select name='%s'> "
                                "from %s", len(specialties), FORM_SELECT_NAME, form_page_url)
                    return specialties
        except Exception as exc:
            logger.warning("Phase 1: failed to fetch form page %s: %s", form_page_url, exc)

    if not specialties:
        logger.warning("Phase 1: no specialty options found; using fallback list")
        specialties = [("0", "All Specialties")]

    return specialties


def _discover_all_urls(state: dict, limit: Optional[int] = None) -> list[str]:
    """Phase 1: Discover all job URLs by iterating through specialty form options.

    The QuickSearch form requires a "Specialties" selection. We iterate through
    ALL options to discover every job. Each submission is paginated until
    exhaustion.
    """
    # Phase 1a: Get all specialty options from the form
    specialties = _get_specialty_options()
    logger.info("Phase 1: discovered %d specialty options to iterate", len(specialties))

    # Phase 1b: For each specialty, POST the form and collect job URLs
    all_urls: list[str] = []
    seen: set[str] = set()
    state["dimensions_total"] = len(specialties)
    dim = 0

    for spec_value, spec_label in specialties:
        dim += 1
        try:
            logger.info("Phase 1b [%d/%d]: submitting form for specialty '%s' (value=%s)",
                        dim, len(specialties), spec_label, spec_value)
            page_urls = _discover_for_specialty(spec_value, spec_label, state, limit)

            new_count = 0
            for u in page_urls:
                if u not in seen:
                    seen.add(u)
                    all_urls.append(u)
                    new_count += 1
            logger.info("Phase 1b [%d/%d]: specialty '%s' -> %d total, %d new (running total %d)",
                        dim, len(specialties), spec_label, len(page_urls), new_count, len(all_urls))

            _write_checkpoint(all_urls)
            state["dimensions_iterated"] = dim

            if limit and len(all_urls) >= limit:
                logger.info("Phase 1b: reached limit=%d, stopping", limit)
                _set_stop_reason(state, "max_pages_hit")
                break

        except Exception as exc:
            logger.warning("Phase 1b [%d/%d]: specialty '%s' failed: %s",
                           dim, len(specialties), spec_label, exc)
            _set_stop_reason(state, "navigate_error")

        if dim < len(specialties):
            time.sleep(DELAY_BETWEEN_REQUESTS)

    if limit:
        all_urls = all_urls[:limit]

    logger.info("Phase 1: Discovered %d total job URLs across %d specialties",
                len(all_urls), dim)
    return all_urls


def _discover_for_specialty(
    spec_value: str,
    spec_label: str,
    state: dict,
    limit: Optional[int] = None,
) -> list[str]:
    """Submit the QuickSearch form for a single specialty and paginate.

    Iterates through result pages via the ``page`` query param until a page
    returns no new job URLs.
    """
    sess = _get_session()
    all_urls: list[str] = []

    # First: POST the form to initiate the search
    post_data = {FORM_SELECT_NAME: spec_value}
    try:
        resp = sess.post(FORM_ACTION, data=post_data, timeout=REQUEST_TIMEOUT,
                         allow_redirects=True)
    except Exception as exc:
        logger.warning("Phase 1b: form POST failed for '%s': %s", spec_label, exc)
        _set_stop_reason(state, "navigate_error")
        return []

    if resp.status_code >= 500:
        logger.warning("Phase 1b: form POST returned HTTP %d for '%s'",
                       resp.status_code, spec_label)
        _set_stop_reason(state, "navigate_error")
        return []

    # Extract URLs from the initial results page
    page_urls = _extract_job_links(resp.text)
    all_urls.extend(page_urls)
    logger.info("Phase 1b: '%s' page 1 -> %d job URLs", spec_label, len(page_urls))

    # Paginate: try the page param on the final URL (after redirects)
    current_url = resp.url
    current_page = 1

    while True:
        if limit and len(all_urls) >= limit:
            break

        next_url = _build_page_url(current_url, current_page + 1)

        time.sleep(DELAY_BETWEEN_REQUESTS)
        try:
            resp2 = sess.get(next_url, timeout=REQUEST_TIMEOUT, allow_redirects=True)
        except Exception as exc:
            logger.warning("Phase 1b: page %d GET failed for '%s': %s",
                           current_page + 1, spec_label, exc)
            _set_stop_reason(state, "navigate_error")
            break

        if resp2.status_code >= 500:
            logger.warning("Phase 1b: page %d returned HTTP %d for '%s'",
                           current_page + 1, resp2.status_code, spec_label)
            _set_stop_reason(state, "navigate_error")
            break

        page_urls = _extract_job_links(resp2.text)
        new_count = len(set(page_urls) - set(all_urls))

        current_page += 1
        logger.info("Phase 1b: '%s' page %d -> %d job URLs (%d new)",
                    spec_label, current_page, len(page_urls), new_count)

        if new_count == 0:
            logger.info("Phase 1b: no new items on page %d for '%s', stopping",
                        current_page, spec_label)
            _set_stop_reason(state, "no_new_items")
            break

        all_urls.extend(page_urls)

        if MAX_PAGES and current_page >= MAX_PAGES:
            logger.info("Phase 1b: reached MAX_PAGES=%d for '%s'", MAX_PAGES, spec_label)
            state["max_pages_hit"] = True
            _set_stop_reason(state, "max_pages_hit")
            break

    return list(dict.fromkeys(all_urls))


